/**
 * 주최자에게 보낼 안내문을 **그 슬롯 값으로 채워** 만든다.
 *
 * 계정을 만들거나 비밀번호를 재발급한 **그 자리**에서 쓴다 — 비밀번호는 그때만 아는 값이라
 * (해시로만 저장된다) 나중에 다시 못 만든다. 그래서 최고관리자는 이걸 복사해 전달만 하면 된다.
 *
 * 문안은 `docs/고객-안내-템플릿.md` 와 맞춘다 — 한쪽만 고치면 화면과 문서가 어긋난다.
 */

/** '2026-07-04' → '2026년 7월 4일' — 안내문에선 숫자만 있으면 오해가 는다 */
function longDate(d: string): string {
  const [y, m, day] = d.split('-')
  return `${y}년 ${Number(m)}월 ${Number(day)}일`
}

/** 기간 한 줄 — 열린 끝은 말로 (안내문이라 화살표는 안 쓴다) */
function periodText(r: DateRange | undefined): string | null {
  if (!r?.start && !r?.end) return null
  if (r.start && r.end) return `${longDate(r.start)} ~ ${longDate(r.end)}`
  return r.start ? `${longDate(r.start)}부터` : `${longDate(r.end!)}까지`
}

/**
 * '2026-07-04' + 15 → '2026년 7월 19일' — 자동 삭제일처럼 **날짜를 못박아야** 하는 자리에 쓴다.
 *
 * **UTC 로 계산한다.** 이 값은 시각이 아니라 달력 날짜라(`DateRange` 주석 참고), 로컬 시간으로
 * 다루면 보는 사람의 타임존에 따라 하루가 밀린다. `new Date('...T00:00:00+09:00')` 를 쓰고
 * `getDate()` 로 읽으면 브라우저가 KST 가 아닐 때 전날이 나온다 — 삭제 예정일이 하루 당겨져
 * 안내되면 그건 그냥 틀린 안내다.
 */
function longDatePlus(d: string, days: number): string {
  const [y, m, day] = d.split('-').map(Number)
  const date = new Date(Date.UTC(y, m - 1, day))
  date.setUTCDate(date.getUTCDate() + days)
  return `${date.getUTCFullYear()}년 ${date.getUTCMonth() + 1}월 ${date.getUTCDate()}일`
}

type GuideFn = (slot: Slot, origin: string, email: string, password: string) => string

/**
 * **`Record` 라 모든 서비스가 필수다.**
 *
 * 삼항(`luckydraw ? … : tarot`)이었을 땐 롤링페이퍼 슬롯 주최자가 **"타로 이벤트 안내"** 를
 * 받았다 — 질문·답변을 채우라는, 그 슬롯엔 있지도 않은 화면을 설명하는 문안이다.
 * 서비스가 늘 때마다 조용히 반복될 종류의 사고라 `Record` 로 막는다.
 */
const GUIDES: Record<ServiceId, GuideFn> = {
  tarot: tarotGuide,
  luckydraw: luckydrawGuide,
  rolling: rollingGuide,
  photozone: photozoneGuide,
  wish: wishGuide,
  poll: pollGuide,
  stamp: stampGuide,
  quiz: quizGuide,
  photocard: photocardGuide,
}

export function buildGuide(slot: Slot, origin: string, email: string, password: string): string {
  return GUIDES[getSlotService(slot)](slot, origin, email, password)
}

