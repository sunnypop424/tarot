/**
 * 방문자 식별자 — **서버로 나가는 유일한 브라우저 로컬 값.**
 *
 * 이 앱엔 방문자 로그인이 없다. 그런데 서버가 "같은 사람의 반복 호출" 을 알아야 하는 자리가
 * 생긴다 (레이트리밋, 뽑기 횟수 제한, 스탬프 중복 방지). 그래서 브라우저가 스스로 만든
 * 익명 uuid 를 들고 다닌다.
 *
 * **이게 사람 식별이 아니라는 걸 분명히 해둔다.** 지우면 새 값이 나오고, 폰을 바꾸면 남남이다.
 * 막을 수 있는 건 실수 연타와 정직한 반복까지고, 작정하고 우회하는 사람은 못 막는다 —
 * 그 한계를 전제로 쓰는 값이지 "1인 1회" 를 보장하는 값이 아니다.
 * 진짜 1인 1회가 필요하면 스태프가 발급하는 코드 같은 **사람이 개입하는 장치**가 있어야 한다.
 *
 * **`locker.ts` 와 파일을 나눈 이유가 이것이다** — 이 값은 서버로 가고, 보관함은 안 간다.
 * 한 파일에 두면 다음 사람이 보관함 내용을 서버로 보내는 코드를 자연스럽게 쓰게 된다.
 */

const KEY = 'tarot-pocket:visitor'

/**
 * 슬롯 스코프가 **아니다.** 한 브라우저에 하나뿐이다 —
 * 슬롯마다 새 값을 주면 레이트리밋이 슬롯을 옮겨 다니는 자동화를 못 센다.
 * 슬롯 격리는 서버가 slug 로 한다 (모든 RPC 의 첫 인자).
 */
export function visitorId(): string {
  try {
    const saved = localStorage.getItem(KEY)
    if (saved) return saved
    const made = crypto.randomUUID()
    localStorage.setItem(KEY, made)
    return made
  } catch {
    /**
     * Safari 프라이빗 모드 등 localStorage 가 막힌 환경.
     * **던지지 않고 일회용 값을 준다** — 여기서 막히면 뽑기·투표가 통째로 안 되는데,
     * 그건 레이트리밋이 조금 헐거워지는 것보다 훨씬 나쁘다.
     * 매 호출마다 다른 값이라 그 브라우저에선 횟수 제한이 사실상 안 걸린다 (IP 캡은 남는다).
     */
    return crypto.randomUUID()
  }
}
