-- 표시는 카운터에서 방문자와 같이 보는 값이다 — 뽑기 전에 뭘 노리는지가 보여야 재미가 산다.
--
-- **레어도와 따로 두는 이유:** 레어도는 확률이고 럭키는 **연출**이다. 레어도 5인데 굳이
-- 강조하고 싶지 않은 카드도 있고(그냥 물량이 적은 것), 레어도 2인데 팬들이 아는 특별한
-- 컷이라 강조하고 싶은 경우도 있다. 하나로 묶으면 그 둘을 못 가른다.
