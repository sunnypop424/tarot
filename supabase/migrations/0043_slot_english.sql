-- 슬롯이 **영어를 지원하나** — 방문자 화면에 한/EN 단추를 띄울지.
--
-- 화면 문구만 영어가 되고 **주최자가 적은 내용은 한국어로 남는다**(질문·상품명·문항·쪽지).
-- 그래서 기본이 꺼짐이다: 해외 팬이 안 오는 행사에 단추가 떠 있으면 눌러볼 거리일 뿐이고,
-- 눌렀을 때 반쪽만 번역된 화면을 보게 된다. 그 한계를 아는 주최자만 켠다
-- (편집기 칸의 힌트가 그걸 그대로 말한다).
--
-- **관리 화면 토글은 이 값과 무관하게 늘 있다** — 그건 "방문자에게 영어를 보여줄까" 가 아니라
-- "이 화면을 쓰는 사람이 한국어를 읽나" 라 다른 질문이고, 주최자 계정을 누구에게 주게 될지
-- 우리가 미리 알 수 없다.

