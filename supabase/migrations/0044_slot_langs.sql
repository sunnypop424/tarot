-- 슬롯이 **어떤 언어를 보여줄지** — `english` 불리언을 언어 목록으로 바꾼다.
--
-- 0043 이 `english boolean` 을 넣었는데, 지원 언어가 넷(한·영·중·일)이 되면서 불리언으로는
-- 표현할 수 없게 됐다. 0043 은 **이번 작업 중에 만든 컬럼이고 아직 아무 슬롯도 안 켰다** —
-- 그래서 옮길 데이터가 없다. 그 컬럼을 지우고 배열로 다시 만든다.
--
-- ── 왜 목록인가 ────────────────────────────────────
-- "영어를 켠다/끈다" 가 아니라 **"이 행사에 오는 사람들의 언어를 고른다"** 가 맞는 질문이다.
-- 일본 팬만 오는 행사에 영어 단추가 떠 있을 이유가 없고, 반대도 마찬가지다.
-- 고른 게 없으면(기본) 방문자 화면에 언어 단추가 아예 안 뜬다 — 한국어 행사가 대부분이다.
--
-- **한국어는 목록에 안 넣는다.** 늘 있는 기본값이라 넣으면 "빼면 한국어가 사라지나" 가 된다.
-- 화면이 `['ko', ...langs]` 로 붙여서 그린다.
--
-- ── 관리 화면은 이 값과 무관하다 ───────────────────
-- 관리 화면 토글은 늘 넷 다 있다. 그건 "방문자에게 무엇을 보여줄까" 가 아니라 "이 화면을 쓰는
-- 사람이 한국어를 읽나" 라 다른 질문이고, 주최자 계정을 누구에게 주게 될지 미리 알 수 없다.

alter table public.slots drop column if exists english;

-- text[] 로 든다 — 값은 'en' · 'zh' · 'ja' (`src/i18n/index.tsx` 의 `LANGS`).
-- **DB 는 값을 검사하지 않는다.** 모르는 코드가 들어와도 화면이 사전을 못 찾아 한국어로
-- 떨어질 뿐이라(폴백이 안전하다) 제약을 걸어 배포를 막을 이유가 없다.
alter table public.slots add column if not exists langs text[] not null default '{}';
