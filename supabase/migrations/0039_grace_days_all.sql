-- 유예를 **모든 서비스 14일로 통일한다.**
--
-- 0009 는 럭키드로우만 14일이었고(배송 명단), 0015 가 모의고사·포토카드·투표·스탬프를 더했다.
-- 나머지 다섯(타로·롤링페이퍼·소원나무·포토존·영상회)은 0 이었다 — "행사 뒤에 꺼낼 게 없다" 는
-- 판단이었다.
--
-- **그 판단이 반쪽이었다.** 롤링페이퍼·소원나무·영상회는 `exportAll` 이 실제로 쪽지 CSV 를
-- 뽑아 준다. 유예가 0 이면 주최자는 **행사가 끝나는 그 순간** 그걸 잃는다 — 마지막 날 밤에
-- 정신없이 부스를 접고 다음 날 받으러 오면 이미 없다. 꺼낼 게 없는 게 아니라, 꺼낼 시간이
-- 없었던 것이다.
--
-- 그리고 서비스마다 다른 유예는 **설명할 수 없다.** 주최자에게 "이 서비스는 2주, 저 서비스는
-- 당일" 이라고 말해야 하고, 화면도 그만큼 갈린다(실제로 대시보드가 전부에게 "종료 후 14일" 이라고
-- 잘못 적고 있었다). 규칙 하나가 맞는 규칙 다섯보다 낫다.
--
-- ── 이 변경이 방문자에게 미치는 영향 ────────────────────────────────
--
-- 정책은 이미 **읽기와 쓰기를 갈라 놨다** (0013 §):
--   · 읽기(방문자) : slot_visible — 행사 + 유예
--   · 쓰기(방문자) : slot_open    — 행사 중에만
--
-- 그래서 유예가 늘어도 **행사 뒤에 글이 남거나 도장이 찍히거나 표가 들어가지 않는다.**
-- 늘어나는 건 "읽을 수 있는 기간" 뿐이다.
--
-- 다만 **서버에 아무것도 안 쓰는 서비스**(타로 뽑기 · 포토존 합성)는 읽기만으로 완전히 동작해서,
-- 유예가 곧 대여 연장처럼 보인다. 그건 **화면이 막는다** — `SlotLayout` 이 종료된 슬롯의
-- 방문자 화면을 종료 안내로 바꾼다. 관리·스태프 화면은 유예 동안 그대로 열려 있다
-- (자료를 꺼내고 남은 선물을 건네는 게 유예의 목적이다).

create or replace function public.slot_grace_days(service text)
  returns int language sql immutable
as $$
  -- 인자는 남겨 둔다 — `slot_visible(period, service)` 의 호출부와 정책 수십 개가 이 시그니처를
  -- 물고 있다. 서비스별로 다시 갈릴 일이 생기면 여기 case 만 되살리면 된다.
  select 14;
$$;

-- 0009 §3 · 0015 가 준 grant 는 `create or replace` 로 유지되지만 그 사실에 기대지 않는다
-- (0010 §3: 이 함수는 **정책이 부른다** — anon 이 EXECUTE 를 잃으면 슬롯이 아무에게도 안 열린다).
grant execute on function public.slot_grace_days(text) to anon, authenticated;

-- ── 자동 삭제는 이미 유예를 따른다 ──────────────────────────────────
-- 0009 §4 의 삭제 대상 조회가 `slot_grace_days` 를 그대로 부르므로, 여기만 고치면
-- 삭제 시점도 같이 밀린다 (마감 +15일 → 모든 서비스가 같은 날짜에 지워진다).
